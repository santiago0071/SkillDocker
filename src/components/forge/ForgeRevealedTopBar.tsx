import React from 'react';
import {
  Activity,
  Sparkles,
  Boxes,
  RotateCcw,
  Edit3,
  Zap,
  Loader2,
  CheckCircle2,
  Save,
  Copy,
  Stethoscope,
  AlertTriangle,
} from 'lucide-react';
import { AiConfig } from '../../core/aiClient.ts';
import { EcosystemTarget } from '../../types/index.ts';

export interface ForgeRevealedTopBarProps {
  lang: 'zh' | 'en';
  t: Record<string, string>;
  skillName: string;
  skillCategory: string;
  skillVersion: string;
  doctorReport: any;
  generatedSource: 'llm' | 'template';
  aiConfig: AiConfig;
  isFineTuning: boolean;
  setIsFineTuning: React.Dispatch<React.SetStateAction<boolean>>;
  setStage: (stage: 'input' | 'revealed') => void;
  handleDeployToWorkspace: (target: EcosystemTarget) => void;
  isDeployingToWorkspace: boolean;
  activeFormatTarget: EcosystemTarget;
  handleDeployGlobal: () => void;
  isDeploying: boolean;
  saveSuccessInfo: { skillName: string; filePath: string; ecosystem: string; time: number } | null;
  setSaveSuccessInfo: React.Dispatch<React.SetStateAction<{ skillName: string; filePath: string; ecosystem: string; time: number } | null>>;
  onOpenSettings?: () => void;
  onOpenDoctor?: (skillName?: string) => void;
  onClose: () => void;
  showToast: (msg: string, type?: 'info' | 'success' | 'error') => void;
}

export const ForgeRevealedTopBar: React.FC<ForgeRevealedTopBarProps> = ({
  lang,
  t,
  skillName,
  skillCategory,
  skillVersion,
  doctorReport,
  generatedSource,
  aiConfig,
  isFineTuning,
  setIsFineTuning,
  setStage,
  handleDeployToWorkspace,
  isDeployingToWorkspace,
  activeFormatTarget,
  handleDeployGlobal,
  isDeploying,
  saveSuccessInfo,
  setSaveSuccessInfo,
  onOpenSettings,
  onOpenDoctor,
  onClose,
  showToast,
}) => {
  return (
    <>
      {/* Top Overview & Action Bar */}
      <div className="px-6 py-2.5 bg-[#0f111c] border-b border-gray-800 flex items-center justify-between flex-shrink-0 flex-wrap gap-2">
        <div className="flex items-center space-x-2.5">
          <span className="text-xs font-bold text-purple-300 font-mono bg-purple-950/60 px-2 py-0.5 rounded border border-purple-500/30">
            {skillName}
          </span>
          <span className="text-[11px] text-gray-400 uppercase">
            {skillCategory} · v{skillVersion}
          </span>
          <div className={`text-xs font-mono font-bold px-2 py-0.5 rounded border flex items-center space-x-1 ${doctorReport.gradeBadgeClass}`}>
            <Activity className="w-3 h-3" />
            <span>{doctorReport.score} {lang === 'zh' ? '分' : 'pts'} · {lang === 'zh' ? doctorReport.gradeLabel : doctorReport.gradeLabelEn}</span>
          </div>

          {/* Real-time Source Transparency Badge */}
          {generatedSource === 'llm' ? (
            <div className="flex items-center space-x-1.5 px-2 py-0.5 rounded-lg border bg-purple-500/15 text-purple-300 border-purple-500/30 text-[11px] font-mono font-semibold" title={lang === 'zh' ? '本内容由真实大模型深度推演生成' : 'Generated by live LLM model'}>
              <Sparkles className="w-3 h-3 text-purple-400 animate-pulse flex-shrink-0" />
              <span>{aiConfig.activeProvider.toUpperCase()} · AI 深度生成</span>
            </div>
          ) : (
            <div className="flex items-center space-x-1.5 px-2 py-0.5 rounded-lg border bg-amber-500/15 text-amber-300 border-amber-500/30 text-[11px] font-mono" title={lang === 'zh' ? '当前未配置或未连通大模型 Key，已启用本地离线智能模板' : 'Offline smart template'}>
              <Boxes className="w-3 h-3 text-amber-400 flex-shrink-0" />
              <span>{lang === 'zh' ? '离线预设模板' : 'Offline Template'}</span>
              {onOpenSettings && (
                <button
                  type="button"
                  onClick={onOpenSettings}
                  className="ml-1 text-[10px] text-amber-400 hover:text-white underline cursor-pointer"
                  title={lang === 'zh' ? '前往配置大模型 Key，开启全自动大模型深度思考' : 'Configure key for live model'}
                >
                  {lang === 'zh' ? '(配置Key启用真实模型)' : '(Config Key)'}
                </button>
              )}
            </div>
          )}
        </div>

        {/* Actions */}
        <div className="flex items-center space-x-2">
          {/* Reset button */}
          <button
            type="button"
            onClick={() => setStage('input')}
            className="flex items-center space-x-1 px-3 py-1.5 rounded-xl text-xs text-gray-400 hover:text-white hover:bg-gray-800 border border-gray-700/60 transition cursor-pointer"
          >
            <RotateCcw className="w-3.5 h-3.5" />
            <span>{t.forgeResetBtn}</span>
          </button>

          {/* Toggle fine-tuning */}
          <button
            type="button"
            onClick={() => setIsFineTuning(!isFineTuning)}
            className={`flex items-center space-x-1 px-3 py-1.5 rounded-xl text-xs font-medium border transition cursor-pointer ${
              isFineTuning
                ? 'bg-purple-600/20 text-purple-300 border-purple-500/50'
                : 'text-gray-300 hover:bg-gray-800 border-gray-700'
            }`}
          >
            <Edit3 className="w-3.5 h-3.5" />
            <span>{t.forgeEditBtn}</span>
          </button>

          {/* 1-Click Deploy to Active Workspace */}
          <button
            type="button"
            onClick={() => handleDeployToWorkspace(activeFormatTarget)}
            disabled={isDeployingToWorkspace}
            className="flex items-center space-x-1.5 px-3.5 py-1.5 rounded-xl bg-gradient-to-r from-emerald-600 to-teal-600 hover:from-emerald-500 hover:to-teal-500 text-white text-xs font-bold transition shadow-lg shadow-emerald-600/20 cursor-pointer disabled:opacity-50"
            title={lang === 'zh' ? '直接将技能写入当前工程目录并立即生效' : 'Write skill directly to active workspace root'}
          >
            {isDeployingToWorkspace ? (
              <Loader2 className="w-3.5 h-3.5 animate-spin" />
            ) : (
              <Zap className="w-3.5 h-3.5 text-yellow-300" />
            )}
            <span>{lang === 'zh' ? '⚡ 一键装载到当前项目' : 'Deploy to Workspace'}</span>
          </button>

          {/* Save to Global Hub */}
          <button
            type="button"
            onClick={() => handleDeployGlobal()}
            disabled={isDeploying || !skillName.trim()}
            className={`flex items-center space-x-1.5 px-3.5 py-1.5 rounded-xl text-xs font-bold transition shadow-lg cursor-pointer ${
              saveSuccessInfo?.skillName === skillName.trim()
                ? 'bg-emerald-600 hover:bg-emerald-500 text-white shadow-emerald-600/30 ring-1 ring-emerald-400'
                : 'bg-gradient-to-r from-purple-600 to-indigo-600 hover:from-purple-500 hover:to-indigo-500 text-white shadow-purple-600/30 disabled:opacity-40'
            }`}
            title={lang === 'zh' ? '保存至本地用户全局技能库' : 'Save to user global skills hub'}
          >
            {isDeploying ? (
              <Loader2 className="w-3.5 h-3.5 animate-spin" />
            ) : saveSuccessInfo?.skillName === skillName.trim() ? (
              <CheckCircle2 className="w-3.5 h-3.5 text-white" />
            ) : (
              <Save className="w-3.5 h-3.5" />
            )}
            <span>
              {saveSuccessInfo?.skillName === skillName.trim()
                ? (lang === 'zh' ? '✓ 已保存到全局库' : '✓ Saved to Global')
                : (lang === 'zh' ? '💾 保存到全局库' : 'Save to Global Hub')}
            </span>
          </button>
        </div>
      </div>

      {/* Global Deploy Success Result Card */}
      {saveSuccessInfo && (
        <div className="mx-6 mt-3 p-3.5 rounded-2xl bg-gradient-to-r from-emerald-950/90 via-[#0e2219] to-[#0d1e18] border border-emerald-500/50 shadow-xl shadow-emerald-950/40 text-xs flex flex-col md:flex-row md:items-center justify-between gap-3 animate-in fade-in slide-in-from-top-2 duration-200">
          <div className="flex items-start md:items-center space-x-3 min-w-0">
            <div className="p-2 rounded-xl bg-emerald-500/20 text-emerald-300 border border-emerald-500/30 flex-shrink-0">
              <CheckCircle2 className="w-5 h-5 text-emerald-400" />
            </div>
            <div className="min-w-0 space-y-1">
              <div className="flex items-center space-x-2 flex-wrap">
                <span className="font-bold text-white text-xs">
                  {lang === 'zh' ? '✓ 技能已成功保存到本地全局库！' : '✓ Successfully saved to global library!'}
                </span>
                <span className="px-1.5 py-0.2 rounded bg-emerald-500/20 text-emerald-300 font-mono text-[10px] border border-emerald-500/30">
                  {saveSuccessInfo.ecosystem}
                </span>
              </div>
              <div className="flex items-center space-x-2 text-[11px] text-gray-300 flex-wrap">
                <span className="text-gray-400 font-sans">{lang === 'zh' ? '真实文件路径:' : 'Disk Path:'}</span>
                <code className="font-mono bg-black/50 px-2 py-0.5 rounded border border-emerald-500/30 text-emerald-300 select-all truncate max-w-md sm:max-w-lg" title={saveSuccessInfo.filePath}>
                  {saveSuccessInfo.filePath}
                </code>
                <button
                  type="button"
                  onClick={() => {
                    navigator.clipboard.writeText(saveSuccessInfo.filePath);
                    showToast(lang === 'zh' ? '已复制技能真实磁盘路径' : 'Copied file path', 'success');
                  }}
                  className="text-[10px] text-emerald-400 hover:text-white underline cursor-pointer flex items-center space-x-1"
                  title="复制文件路径"
                >
                  <Copy className="w-3 h-3" />
                  <span>{lang === 'zh' ? '复制完整路径' : 'Copy Path'}</span>
                </button>
              </div>
            </div>
          </div>

          <div className="flex items-center space-x-2 flex-shrink-0 self-end md:self-auto flex-wrap">
            <button
              type="button"
              onClick={() => setSaveSuccessInfo(null)}
              className="px-3 py-1.5 rounded-xl bg-gray-900/80 hover:bg-gray-800 text-gray-300 border border-white/[0.08] text-xs font-medium transition cursor-pointer"
            >
              {lang === 'zh' ? '留在工坊微调' : 'Keep Editing'}
            </button>
            {onOpenDoctor && (
              <button
                type="button"
                onClick={() => onOpenDoctor(saveSuccessInfo.skillName)}
                className="px-3 py-1.5 rounded-xl bg-purple-600/30 hover:bg-purple-600/50 text-purple-200 border border-purple-500/50 text-xs font-semibold transition cursor-pointer flex items-center space-x-1 shadow-sm"
                title={lang === 'zh' ? '移步技能医生进行全方位质检与深度优化' : 'Inspect with Skills Doctor'}
              >
                <Stethoscope className="w-3.5 h-3.5 text-purple-300" />
                <span>{lang === 'zh' ? '🩺 移步医生质检' : 'Doctor Check'}</span>
              </button>
            )}
            <button
              type="button"
              onClick={onClose}
              className="px-3.5 py-1.5 rounded-xl bg-emerald-600 hover:bg-emerald-500 text-white text-xs font-bold transition shadow-md shadow-emerald-600/30 flex items-center space-x-1.5 cursor-pointer"
            >
              <span>{lang === 'zh' ? '返回并在主列表中查看 →' : 'View in Library →'}</span>
            </button>
          </div>
        </div>
      )}

      {/* Skill Doctor Diagnostics Banner (体检医生看板) */}
      <div className="px-6 py-2.5 bg-[#090b14] border-b border-gray-800/80 flex items-center justify-between text-xs flex-wrap gap-2 text-gray-300">
        <div className="flex items-center space-x-3 flex-wrap">
          <span className="font-semibold text-purple-300 flex items-center space-x-1">
            <span>{lang === 'zh' ? '🩺 体检诊断:' : '🩺 Skill Doctor:'}</span>
          </span>
          
          {/* Token Count Badge */}
          <span className="px-2 py-0.5 rounded bg-gray-800 text-[11px] font-mono text-gray-300 border border-gray-700">
            {lang === 'zh'
              ? `预估 ~${doctorReport.tokens} Tokens (${doctorReport.charCount} 字符 / ${doctorReport.lineCount} 行)`
              : `Est. ~${doctorReport.tokens} Tokens (${doctorReport.charCount} chars / ${doctorReport.lineCount} lines)`}
          </span>

          {/* YAML Validation Badge */}
          <span className={`px-2 py-0.5 rounded text-[11px] font-mono border ${
            doctorReport.yamlValidation.valid
              ? 'bg-emerald-500/10 text-emerald-300 border-emerald-500/30'
              : 'bg-amber-500/10 text-amber-300 border-amber-500/30'
          }`}>
            {doctorReport.yamlValidation.valid
              ? (lang === 'zh' ? '✓ YAML Frontmatter 合规' : '✓ Valid YAML Frontmatter')
              : (lang === 'zh' ? '⚠️ YAML 格式需完善' : '⚠️ YAML Needs Improvement')}
          </span>

          {/* 5-Dimensional Core Defensive Items */}
          <div className="hidden md:flex items-center space-x-1.5 text-[10px]">
            {doctorReport.items.map((item: any) => (
              <span
                key={item.id}
                className={`px-1.5 py-0.5 rounded border ${
                  item.passed
                    ? 'bg-emerald-500/10 text-emerald-300 border-emerald-500/20'
                    : 'bg-gray-800/60 text-gray-500 border-gray-700/50'
                }`}
                title={lang === 'zh' ? item.detail : (item.detailEn || item.detail)}
              >
                {item.passed ? '✓' : '✗'} {lang === 'zh' ? (item.shortLabelZh || item.title.split(' ')[0]) : (item.shortLabelEn || item.titleEn || item.title)}
              </span>
            ))}
          </div>
        </div>

        {/* Warnings / Diagnostic Tips */}
        {doctorReport.diagnostics.length > 0 && (
          <div className="text-[11px] text-amber-400/90 truncate max-w-sm flex items-center space-x-1">
            <AlertTriangle className="w-3 h-3 flex-shrink-0" />
            <span className="truncate">
              {lang === 'zh'
                ? doctorReport.diagnostics[0].message
                : (doctorReport.diagnostics[0].messageEn || doctorReport.diagnostics[0].message)}
            </span>
          </div>
        )}
      </div>
    </>
  );
};
